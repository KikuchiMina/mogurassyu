#include "../../Header/scene/title.h"

//=========================================================
// 静的メンバ変数宣言
//=========================================================
CBg* CTitle::pBg = NULL;
int CTitle::m_Data = 0;

//=========================================================
//マクロ定義
//=========================================================
#define CLEAR_TEXTURE "data\\TEXTURE\\title.png"	// タイトル時に出すテクスチャ

//=========================================================
// コンストラクタ
//=========================================================
CTitle::CTitle() : CScene(CScene::MODE_TITLE)
{
}

//=========================================================
// デストラクタ
//=========================================================
CTitle::~CTitle()
{
}

//=========================================================
// 生成処理
//=========================================================
void CTitle::Create(void)
{
	// 背景の生成
	pBg = CBg::Create(D3DXVECTOR3(0.0f, 0.0f, 0.0f), SCREEN_WIDTH, SCREEN_HEIGHT, CBg::BGTEX_TITLE);
}

//=========================================================
// テクスチャの読み込み処理
//=========================================================
HRESULT CTitle::Load(void)
{
	// 背景の読み込み
	pBg->Load(CLEAR_TEXTURE);

	return S_OK;
}

//=========================================================
// テクスチャの破棄処理
//=========================================================
void CTitle::Unload(void)
{
	// 背景の破棄
	pBg->Unload();
}

//=========================================================
// 初期化処理
//=========================================================
HRESULT CTitle::Init(void)
{
	// テクスチャの読み込み
	HRESULT hresult = Load();
	if (hresult == S_FALSE)
	{
		return S_FALSE;
	}

	// 生成処理
	Create();

	return S_OK;
}

//=========================================================
// 終了処理
//=========================================================
void CTitle::Uninit(void)
{
	// テクスチャの破棄
	Unload();
}

//=========================================================
// 更新処理
//=========================================================
void CTitle::Update(void)
{
	CInputKeyboard* pKeyBoaed = CManager::GetKeyboard();
	CRenderer* pRenderer = CManager::GetRenderer();

	// タイトルへ戻る
	if (pKeyBoaed->GetKeyboardTrigger(DIK_RETURN) == true)
	{
		// ゲームシーンの再読み込み
		CFade::SetFade(CScene::MODE_GAME);
	}
}

