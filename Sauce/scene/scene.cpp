//=========================================================
// 画面の生成処理
//=========================================================
CScene* CScene::Create(MODE mode)
{
	CScene* pScene = NULL;

	if (pScene == NULL)
	{
		// 指定されたモードを設定
		switch (mode)
		{
		case MODE_TITLE:		// タイトル画面
			pScene = new CTitle;   
			break;				   
		case MODE_STAGESELECT:	// ステージ選択画面
			break;				   
		case MODE_GAME:			// ゲーム画面
			pScene = new CGame;	   
			break;				   
		case MODE_CLEAR:		// ゲームクリア画面
			pScene = new CClear;   
			break;				   
		case MODE_OVER:			// ゲームオーバー画面
			pScene = new COver;	   
		case MODE_RANKING:		// ランキング画面
			pScene = new COver;
			break;
		}

		if (pScene != NULL)
		{
			// 画面の初期化処理
			pScene->Init();

			return pScene;
		}
	}

	return pScene;
}

