#include "../../Header/scene/clear.h"

//=========================================================
// 静的メンバ変数宣言
//=========================================================
CBg* CClear::pBg = CClear::GetBg();

//=========================================================
//マクロ定義
//=========================================================
#define CLEAR_TEXTURE "data\\TEXTURE\\clear.jpg"	// クリア時に出すテクスチャ

//=========================================================
// コンストラクタ
//=========================================================
CClear::CClear() : CScene(CScene::MODE_TITLE)
{
}

//=========================================================
// デストラクタ
//=========================================================
CClear::~CClear()
{
}

//=========================================================
// 生成処理
//=========================================================
void CClear::Create(void)
{
	// 背景の生成
	pBg = CBg::Create(D3DXVECTOR3(0.0f, 0.0f, 0.0f), SCREEN_WIDTH, SCREEN_HEIGHT, CBg::BGTEX_CLEAR);
}

//=========================================================
// テクスチャの読み込み処理
//=========================================================
HRESULT CClear::Load(void)
{
	// 背景の読み込み
	pBg->Load(CLEAR_TEXTURE);

	return S_OK;
}

//=========================================================
// テクスチャの破棄処理
//=========================================================
void CClear::Unload(void)
{
	// 背景の破棄
	pBg->Unload();
}

//=========================================================
// 初期化処理
//=========================================================
HRESULT CClear::Init(void)
{
	// テクスチャの読み込み
	HRESULT hresult = Load();
	if (hresult == S_FALSE)
	{
		return S_FALSE;
	}

	// 生成処理
	Create();

	return S_OK;
}

//=========================================================
// 終了処理
//=========================================================
void CClear::Uninit(void)
{
	// テクスチャの破棄
	Unload();
}

//=========================================================
// 更新処理
//=========================================================
void CClear::Update(void)
{
	CInputKeyboard* pInputKeyboard = CManager::GetKeyboard();
	CRenderer* pRenderer = CManager::GetRenderer();

	//-------------------------------------
	// タイトルへ戻る
	if (pInputKeyboard->GetKeyboardTrigger(DIK_RETURN) == true)
	{
		// ゲームシーンの再読み込み
		CFade::SetFade(CScene::MODE_TITLE);
	}
	
}

